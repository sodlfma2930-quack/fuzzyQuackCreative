// Own-key check so ?r=constructor and other prototype keys are rejected.
export function isType(key) {
  return typeof key === 'string' && Object.hasOwn(types, key)
}

// Ties go to whichever tied type was picked most recently.
export function decide(picks) {
  const score = {}
  picks.forEach((t) => (score[t] = (score[t] || 0) + 1))
  const max = Math.max(...Object.values(score))
  for (let i = picks.length - 1; i >= 0; i--) {
    if (score[picks[i]] === max) return picks[i]
  }
}
